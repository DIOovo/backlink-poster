#!/usr/bin/env node
/**
 * 从 playwright 提取 InjectedScript bundle，生成 public/injected.js。
 *
 * 来源优先级：
 *   1) node_modules/playwright-core/lib/generated/injectedScriptSource.js （官方 npm，建议作为 devDependency）
 *   2) 环境变量 PW_INJECTED_SOURCE 指向的文件
 *   3) ../playwright-crx/playwright/packages/playwright-core/src/generated/injectedScriptSource.ts （本地 checkout）
 *
 * 产物是纯静态 IIFE（无运行时 eval，符合 MV3 CSP），在 content script isolated world
 * 暴露全局 __aifillInjected（InjectedScript 实例；初始化失败为 null，调用方需兜底）。
 *
 * 用法：npm run gen:injected
 */
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);

function findSourceFile() {
  const candidates = [
    path.join(root, 'node_modules/playwright-core/lib/generated/injectedScriptSource.js'),
    process.env.PW_INJECTED_SOURCE,
    path.join(root, '../playwright-crx/playwright/packages/playwright-core/src/generated/injectedScriptSource.ts'),
  ].filter(Boolean);
  for (const f of candidates) {
    if (fs.existsSync(f)) return f;
  }
  throw new Error(
    '找不到 injectedScriptSource。请安装 devDependency playwright-core（npm i -D playwright-core），' +
    '或用 PW_INJECTED_SOURCE 指定文件路径。'
  );
}

/** 从 injectedScriptSource 文件读取 source 字符串 */
function loadSource(sourceFile) {
  if (sourceFile.endsWith('.js')) {
    const s = require(sourceFile).source;
    if (typeof s !== 'string' || s.length < 100_000) {
      throw new Error('提取到的 source 异常（长度 ' + (s && s.length) + '）');
    }
    return s;
  }
  return extractSourceFromTs(fs.readFileSync(sourceFile, 'utf8'));
}

/** 从 .ts 源码中提取 `export const source = "..."` */
function extractSourceFromTs(text) {
  const m = text.match(/source\s*=\s*("(?:\\.|[^"\\])*")/);
  if (!m) throw new Error('无法从文件中提取 source 字符串字面量');
  const s = vm.runInNewContext('(' + m[1] + ')');
  if (typeof s !== 'string' || s.length < 100_000) throw new Error('提取到的 source 异常（长度 ' + (s && s.length) + '）');
  return s;
}

function detectVersion(sourceFile) {
  try {
    // node_modules/playwright-core/lib/generated/... → 向上找 package.json
    let dir = path.dirname(sourceFile);
    for (let i = 0; i < 5; i++) {
      const pkg = path.join(dir, 'package.json');
      if (fs.existsSync(pkg)) {
        const j = JSON.parse(fs.readFileSync(pkg, 'utf8'));
        if (j.name === 'playwright-core' || j.name === 'playwright-internal') return j.version || 'unknown';
      }
      dir = path.dirname(dir);
    }
  } catch { /* ignore */ }
  return 'unknown';
}

const sourceFile = findSourceFile();
const source = loadSource(sourceFile);
const version = detectVersion(sourceFile);

const wrapper = [
  '// AUTO-GENERATED by scripts/gen-injected.mjs — DO NOT EDIT BY HAND.',
  `// Playwright InjectedScript bundle (playwright-core ${version}).`,
  '// Regenerate: npm run gen:injected',
  'var __aifillInjected = (() => {',
  '  try {',
  '    var module = { exports: {} };',
  source,
  '    return new (module.exports.InjectedScript())(window, {',
  '      isUnderTest: false,',
  "      sdkLanguage: 'javascript',",
  "      testIdAttributeName: 'data-testid',",
  '      stableRafCount: 16,',
  "      browserName: 'chromium',",
  '      inputFileRoleTextbox: false,',
  '      customEngines: []',
  '    });',
  '  } catch (e) {',
  "    console.warn('[AI Form Filler] Playwright injected init failed:', e);",
  '    return null;',
  '  }',
  '})();',
  '',
].join('\n');

const out = path.join(root, 'public/injected.js');
fs.writeFileSync(out, wrapper);
console.log(`generated ${path.relative(root, out)} (${wrapper.length} bytes, playwright-core ${version}, from ${path.relative(root, sourceFile)})`);
